/// <reference types="node" />
// Builds src/tables/*.ts from the WHATWG Encoding Standard's indexes and labels, plus the
// charset aliases iconv-lite accepts. Run with `pnpm generate` in packages/charset.
import { mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { gzipSync } from 'node:zlib'

const spec = 'https://encoding.spec.whatwg.org'
const out = new URL('../src/tables/', import.meta.url)

type Index = (number | null)[]
type Encodings = { heading: string; encodings: { name: string; labels: string[] }[] }[]

const indexes = (await (await fetch(`${spec}/indexes.json`)).json()) as Record<string, unknown>
const encodings = (await (await fetch(`${spec}/encodings.json`)).json()) as Encodings
const index = (name: string) => indexes[name] as Index

const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'

function packInts(values: readonly number[]): string {
  let text = ''
  for (let value of values) {
    while (value >= 32) {
      text += alphabet[32 | (value & 31)]
      value = Math.floor(value / 32)
    }
    text += alphabet[value]
  }
  return text
}

// unpackIndex() in src/internal/tables.ts reads this format.
function packIndex(entries: Index, start = 0): string {
  const values: number[] = []
  let previous = 0
  let run = 0
  let skip = 0
  const flush = () => {
    if (run) values.push(run * 4 + 2)
    if (skip) values.push(skip * 4 + 3)
    run = skip = 0
  }
  for (let pointer = start; pointer < entries.length; pointer++) {
    const codePoint = entries[pointer] ?? null
    if (codePoint === null) {
      if (run) flush()
      skip++
      continue
    }
    if (skip) flush()
    if (codePoint === previous + 1) run++
    else {
      flush()
      const delta = codePoint - previous
      values.push(delta >= 0 ? delta * 4 : -delta * 4 + 1)
    }
    previous = codePoint
  }
  flush()
  return packInts(values)
}

mkdirSync(out, { recursive: true })
const sizes: string[] = []
function write(file: string, body: string) {
  const text = `// Generated by scripts/generate.ts from ${spec}/. Do not edit.\n${body}`
  writeFileSync(new URL(file, out), text)
  sizes.push(`${file}: ${text.length} B, ${gzipSync(text).length} B gzipped`)
}

const camel = (name: string) =>
  name
    .toLowerCase()
    .replace(/^iso-(\d+)-/, 'iso$1_')
    .replace(/-(\w)/g, (_, c: string) => c.toUpperCase())

const singleByte = encodings.find((group) => group.heading === 'Legacy single-byte encodings')!
write(
  'single-byte.ts',
  singleByte.encodings
    .filter(({ name }) => name !== 'ISO-8859-8-I')
    .map(
      ({ name }) =>
        `export const ${camel(name)}: string = '${packIndex(index(name.toLowerCase()))}'\n`,
    )
    .join(''),
)

write('jis0208.ts', `export const jis0208: string = '${packIndex(index('jis0208'))}'\n`)
write(
  'iso-2022-jp-katakana.ts',
  `export const katakana: string = '${packIndex(index('iso-2022-jp-katakana'))}'\n`,
)
write('euc-kr.ts', `export const eucKr: string = '${packIndex(index('euc-kr'))}'\n`)

// The Big5 encoder never uses pointers below (0xA1 - 0x81) * 157, the HKSCS extensions.
const big5Start = (0xa1 - 0x81) * 157
write(
  'big5.ts',
  `export const big5Start = ${big5Start}\nexport const big5: string = '${packIndex(index('big5'), big5Start)}'\n`,
)

const ranges = indexes['gb18030-ranges'] as [number, number][]
write(
  'gb18030.ts',
  `export const gb18030: string = '${packIndex(index('gb18030'))}'\n` +
    `export const gb18030Ranges: string = '${packInts(ranges.flatMap(([pointer, codePoint], i) => (i ? [pointer - ranges[i - 1]![0], codePoint - ranges[i - 1]![1]] : [pointer, codePoint])))}'\n`,
)

const canonicalize = (label: string) => label.toLowerCase().replace(/:\d{4}$|[^0-9a-z]/g, '')

const names = encodings.flatMap((group) => group.encodings.map((encoding) => encoding.name))
const labels = new Map<string, string>()
for (const { name, labels: list } of encodings.flatMap((group) => group.encodings)) {
  for (const label of list) {
    const key = canonicalize(label)
    const existing = labels.get(key)
    if (existing && existing !== name) throw new Error(`${label} collides with ${existing}`)
    labels.set(key, name)
  }
}

// iconv-lite resolves a name by following string aliases to a codec key. The DBCS codec keys
// and the Unicode codecs don't share a canonical form with a WHATWG label, so they're listed.
const iconvCodecs: Record<string, string> = {
  utf8: 'UTF-8',
  ucs2: 'UTF-16LE',
  utf16: 'UTF-16LE',
  utf16be: 'UTF-16BE',
  shiftjis: 'Shift_JIS',
  eucjp: 'EUC-JP',
  cp936: 'GBK',
  gbk: 'GBK',
  gb18030: 'gb18030',
  cp949: 'EUC-KR',
  cp950: 'Big5',
  big5hkscs: 'Big5',
  maccyrillic: 'x-mac-cyrillic',
}
const iconv = createRequire(import.meta.url)('iconv-lite') as {
  encode(text: string, encoding: string): unknown
  encodings: Record<string, unknown>
}
iconv.encode('', 'utf8')
const iconvOnly: string[] = []
for (const key of Object.keys(iconv.encodings)) {
  let codec = key
  while (typeof iconv.encodings[codec] === 'string') codec = iconv.encodings[codec] as string
  const name = iconvCodecs[codec] ?? labels.get(codec)
  if (!name) {
    iconvOnly.push(key)
    continue
  }
  if (!labels.has(key)) labels.set(key, name)
}

const sorted = [...labels].sort(([a], [b]) => (a < b ? -1 : 1))
const quote = (key: string) => (/^[a-z_][a-z0-9_]*$/.test(key) ? key : `'${key}'`)
write(
  'labels.ts',
  `export type CharsetName =\n${names.map((name) => `  | '${name}'`).join('\n')}\n\n` +
    `export const labels: Record<string, CharsetName> = {\n${sorted.map(([key, name]) => `  ${quote(key)}: '${name}',`).join('\n')}\n}\n`,
)

console.log(sizes.join('\n'))
console.log(`iconv-lite names with no WHATWG encoding: ${iconvOnly.join(', ')}`)
