/// <reference types="node" />
// Builds src/internal/bidi.ts with the bidi classes that src/internal/bidiRule.ts uses to apply the
// bidi rule of RFC 5893. Run with `pnpm generate` in packages/idna.
import { writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const version = '18.0.0';
const base = `https://www.unicode.org/Public/${version}`;
const size = 0x110000;

async function lines(path: string): Promise<string[][]> {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) {
    throw new Error(`${path}: ${response.status}`);
  }
  const text = await response.text();
  if (!text.includes(version)) {
    throw new Error(`${path} is not version ${version}`);
  }
  return text
    .split('\n')
    .map((line) => line.replace(/#.*/, '').trim())
    .filter((line) => line !== '')
    .map((line) => line.split(';').map((field) => field.trim()));
}

function* codePoints(field: string): Generator<number> {
  const [start, end = start] = field.split('..').map((hex) => parseInt(hex, 16));
  for (let cp = start; cp <= end; cp++) {
    yield cp;
  }
}

// The groups of bidi classes that the bidi rule tells apart, numbered as in src/internal/bidiRule.ts.
// Group 0 holds the classes that the rule forbids in every label, such as WS and B.
const groups: Record<string, number> = {
  L: 1,
  R: 2,
  AL: 2,
  AN: 3,
  EN: 4,
  ES: 5,
  CS: 5,
  ET: 5,
  ON: 5,
  BN: 5,
  NSM: 6,
};

const valid = new Uint8Array(size);
for (const [field, status] of await lines('idna/IdnaMappingTable.txt')) {
  if (status === 'valid' || status === 'deviation') {
    for (const cp of codePoints(field)) {
      valid[cp] = 1;
    }
  }
}

const group = new Uint8Array(size);
for (const [field, name] of await lines('ucd/extracted/DerivedBidiClass.txt')) {
  for (const cp of codePoints(field)) {
    group[cp] = groups[name] ?? 0;
  }
}

// Runs of code points in the same group, each stored as one integer, (length - 1) * 8 + group. A
// code point that IDNA doesn't allow is counted in the run before it, because the URL host parser
// rejects it before the bidi rule runs.
const runs: number[] = [];
let current = -1;
let length = 0;
for (let cp = 0; cp < size; cp++) {
  const next = valid[cp] ? group[cp] : current;
  if (next === current) {
    length++;
  } else {
    if (current >= 0) {
      runs.push((length - 1) * 8 + current);
    }
    current = next;
    length = 1;
  }
}
runs.push((length - 1) * 8 + current);

const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

// unpackInts() in src/internal/bidiRule.ts reads this format.
function packInts(numbers: readonly number[]): string {
  let text = '';
  for (let value of numbers) {
    while (value >= 32) {
      text += alphabet[32 | (value & 31)];
      value = Math.floor(value / 32);
    }
    text += alphabet[value];
  }
  return text;
}

const source =
  `// Generated by scripts/generate.ts from Unicode ${version}. Do not edit.\n` +
  `export const runs: string =\n  '${packInts(runs)}';\n`;
writeFileSync(new URL('../src/internal/bidi.ts', import.meta.url), source);

console.log(`${runs.length} runs: ${source.length} bytes, ${gzipSync(source).length} gzipped`);
